let lang = storage.get(LANG_KEY) === "en" ? "en" : "zh";

export const getLang = () => lang;

export function t(key, vars) {
  let s = DICT[lang][key];
  if (vars && vars.n === 1 && DICT[lang][key + ".one"]) s = DICT[lang][key + ".one"];
  if (s == null) s = DICT.zh[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return s;
}

/** Both languages' text for a key (search matches either, whatever the UI language). */
export const tBoth = (key) => [DICT.zh[key], DICT.en[key]].filter(Boolean);

/** Every name a school goes by (short and full, zh and en), for search. */
export function schoolAliases(code) {
  const e = SCHOOLS[code];
  return e ? [code, ...e.zh, ...e.en] : [code];
}

/** Every school code with a name, in the dictionary's order. */
export const schoolCodes = () => Object.keys(SCHOOLS);

export function schoolName(code, full = false) {
  const entry = SCHOOLS[code];
  return entry ? entry[lang][full ? 1 : 0] : code;
}

export function setLang(next) {
  lang = next === "en" ? "en" : "zh";
  storage.set(LANG_KEY, lang);
  applyLang();
}

/** Reflect the language on <html> and on every static [data-i18n] node in the shell. */
export function applyLang(root = document) {
  const html = document.documentElement;
  html.lang = lang === "en" ? "en" : "zh-Hant-TW";
  html.dataset.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
}
